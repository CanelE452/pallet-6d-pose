"""Inert target-context crop math. No file/model/label access."""
import numpy as np

def query_extent(query8):
    q=np.asarray(query8,dtype=np.float64)
    if q.shape!=(8,2): return None
    good=np.isfinite(q).all(1)&~(q==[-1,-1]).all(1)
    if good.sum()<2:return None
    lo=q[good].min(0);hi=q[good].max(0)
    if not (hi>lo).all():return None
    return np.r_[lo,hi].tolist()

def valid_box(box):
    if box is None:return False
    b=np.asarray(box,dtype=np.float64)
    return b.shape==(4,) and np.isfinite(b).all() and b[2]>b[0] and b[3]>b[1]

def target_context_grid(box,out_hw=(224,224)):
    """Native integer pixel-centre coordinates; no clipping or q alteration.
    Box endpoints are interpreted in the same continuous native coordinate system
    as q. The M samples lie strictly inside [lo,hi], at lo+(j+.5)*span/M.
    This is a prospective explicit sampling rule, not a PIL crop equivalence claim.
    """
    if not valid_box(box):raise ValueError('No finite positive input-derived box')
    h,w=map(int,out_hw)
    if h<1 or w<1:raise ValueError('Invalid output size')
    x0,y0,x1,y1=np.asarray(box,dtype=np.float64)
    xs=x0+(np.arange(w)+.5)*(x1-x0)/w
    ys=y0+(np.arange(h)+.5)*(y1-y0)/h
    return np.stack(np.meshgrid(xs,ys),-1)

def sample_target_context(rgb,box,out_hw=(224,224)):
    """Future in-memory bilinear helper; float32 HWC RGB + bool valid.
    Zero outside each native neighbor; valid means all positive-weight neighbors
    exist. No source pixel is read or generated by importing this module.
    """
    rgb=np.asarray(rgb)
    if rgb.ndim!=3 or rgb.shape[2]!=3:raise ValueError('Expected HWC RGB')
    H,W=rgb.shape[:2];g=target_context_grid(box,out_hw);x=g[...,0];y=g[...,1]
    ix=np.floor(x).astype(np.int64);iy=np.floor(y).astype(np.int64);dx=x-ix;dy=y-iy
    out=np.zeros((*x.shape,3),np.float64);valid=np.ones(x.shape,bool)
    for ox,oy,weight in((0,0,(1-dx)*(1-dy)),(1,0,dx*(1-dy)),(0,1,(1-dx)*dy),(1,1,dx*dy)):
        xx=ix+ox;yy=iy+oy;inside=(xx>=0)&(xx<W)&(yy>=0)&(yy<H)
        out+=rgb[np.clip(yy,0,H-1),np.clip(xx,0,W-1)].astype(np.float64)*(weight*inside)[...,None]
        valid&=inside|(weight==0)
    return out.astype(np.float32),valid
