def fixed_choice(frame,pools,costs,path,omitted=None):
    """Only comparator scores change; original eligibility and output roles stay."""
    def ranked(stage,family):
        candidates=pools.get((frame['id'],stage,family),[])
        scores=None if omitted is None else {c['candidate_id']:
            float(c['original_record']['objective'])-float(costs[(frame['id'],c['candidate_id'])]['weighted_components'][omitted])
            for c in candidates}
        return rank_retained(candidates,scores),scores
    selected=frame['selected_family'];stage=frame['stages']
    if path=='G10_ONLY':
        family_scores=[]
        for index,family in enumerate(FAMILIES):
            metadata=stage['G10']['families'][index]
            ranked_candidates,scores=ranked('G10',family)
            if not metadata['accepted']:continue
            if not ranked_candidates:raise ValueError('Accepted family lacks original retained candidates')
            winner=ranked_candidates[0]
            score=winner['original_record']['objective'] if scores is None else scores[winner['candidate_id']]
            family_scores.append((float(score),index,family))
        selected=min(family_scores)[2] if family_scores else FAMILIES[0]
        chosen=stage['G13']['families'][FAMILIES.index(selected)]['winner_candidate_id']
    elif path=='G13_INTERNAL_ONLY':
        values,_=ranked('G13',selected)
        chosen=values[0]['candidate_id'] if values else None
    else:raise ValueError('Only the two predeclared isolated stage paths are allowed')
    return dict(family=selected,candidate_id=chosen,
        uses_original_family_output=path=='G10_ONLY',
        cached_G13_reuse=frame['cached_g13_no_typed_revocation'])


def summarize(records,cohort,variant):
    chosen=[r for r in records if r['variant']==variant and
        (cohort=='PRIMARY' and r['partition']!='CAL' or r['partition']==cohort)]
    transitions=Counter(r['transition'] for r in chosen)
    counts=Counter(r['new_success'] for r in chosen)
    base_success=sum(r['base_success'] for r in chosen)
    recovery=transitions['recovery'];damage=transitions['damage']
    assert recovery-damage==counts[True]-base_success
    sums={};stats={}
    # Sum paired and grouped differences using exact decimals of the recorded
    # float endpoints. This preserves the identity even for extreme finite
    # retained poses, whose float ULP can exceed a small absolute cm tolerance.
    with localcontext() as context:
        context.prec=80
        for key in ('translation_cm','rotation_deg'):
            available=[r for r in chosen if r['new_'+key] is not None and r['base_'+key] is not None]
            delta=lambda r:Decimal.from_float(r['new_'+key])-Decimal.from_float(r['base_'+key])
            total=sum((delta(r) for r in available),Decimal(0))
            groups={g:sum((delta(r) for r in available if r['transition']==g),Decimal(0))
                    for g in ('both_success','recovery','damage','both_failure')}
            assert sum(groups.values(),Decimal(0))==total
            new_sum=sum((Decimal.from_float(r['new_'+key]) for r in available),Decimal(0))
            old_sum=sum((Decimal.from_float(r['base_'+key]) for r in available),Decimal(0))
            assert new_sum-old_sum==total
            sums[key]=dict(sum_delta=str(total),group_sums={g:str(x) for g,x in groups.items()},
                exact_pair_group_identity=True,mean_delta=float(total/len(available)) if available else None,
                common_available=len(available))
            values=[r['new_'+key] for r in available]
            stats[key]=dict(mean=statistics.mean(values) if values else None,
                SD=statistics.stdev(values) if len(values)>1 else None,
                variance=statistics.variance(values) if len(values)>1 else None,max=max(values) if values else None)
    return dict(cohort=cohort,variant=variant,N=len(chosen),base_success=base_success,new_success=counts[True],
        recovery=recovery,damage=damage,both_success=transitions['both_success'],both_failure=transitions['both_failure'],
        exact_recovery_minus_damage_identity=True,continuous=stats,paired_delta=sums,
        fallback_output_rows=sum(r['new_candidate_id'] is None for r in chosen),
        family_changed=sum(r['family_changed'] for r in chosen),candidate_changed=sum(r['candidate_changed'] for r in chosen),
        disclaimer=DISCLAIMER)


def run(parent,root,output):
    parent,root,output=map(Path,(parent,root,output));output.mkdir(parents=True,exist_ok=False)
    protocol=read(root/'INFLUENCE_PROTOCOL.json')
    assert read(root/'SOURCE_BINDINGS.json')['source_and_input_parity']
    assert read(root/'selection_v1/SELECTION_REPLAY.json')['all_passed']
    assert read(root/'cost_v1/COST_SUMMARY.json')['all_complete']
    assert read(root/'metrics_v2/METRIC_CHECK.json')['all_pass']
    assert protocol['actual_additive_families']==['full_BI','partial_normal','outline']
    records=[]
    with timed_stage(root,'predeclared_fixed_bank_rank_influence',new_pose_calls=0):
        frames=list(rows(root/'selection_v1/FRAME_SELECTIONS.jsonl.gz'))
        candidates=list(rows(root/'selection_v1/RETAINED_CANDIDATES.jsonl.gz'))
        costs={(r['id'],r['candidate_id']):r for r in rows(root/'cost_v1/CANDIDATE_COSTS.jsonl.gz')}
        metrics={(r['id'],r['candidate_id']):r['metric'] for r in rows(root/'metrics_v2/CANDIDATE_METRICS.jsonl.gz')}
        pools=defaultdict(list)
        for candidate in candidates:pools[(candidate['id'],candidate['stage'],candidate['family'])].append(candidate)
        assert len(candidates)==len(costs)==len(metrics)==11603
        assert all(c['status']=='COMPLETE' for c in costs.values())
        assert all(c['actual_prior_weight']==0 for c in costs.values())
        references=read(parent/'score_v2/FIXED_REFERENCES.json')['references']
        baseline={r['id']:r for r in csv_rows(parent/'score_v2/ROW_METRICS.csv') if r['arm']=='E0'}
        replay=[]
        with FixedPoseOnly() as guard:
            for frame in frames:
                for path in protocol['paths']:
                    baseline_choice=fixed_choice(frame,pools,costs,path)
                    assert baseline_choice['family']==frame['selected_family']
                    assert baseline_choice['candidate_id']==frame['selected_candidate_id']
                    replay.append(dict(id=frame['id'],path=path,original_selection_exact=True))
                    for family in protocol['actual_additive_families']:
                        choice=fixed_choice(frame,pools,costs,path,family)
                        row=baseline[frame['id']]
                        if choice['candidate_id'] is not None:
                            score=metrics[(frame['id'],choice['candidate_id'])]
                        else:
                            pose=frame['stages']['G13']['families'][FAMILIES.index(choice['family'])]['published_actual_pose']
                            score=metric(pose,references[frame['partition']][frame['id']])
                        base_good=row['success_le5']=='True';new_good=score['success_le5'] is True
                        transition='both_success' if base_good and new_good else 'damage' if base_good else 'recovery' if new_good else 'both_failure'
                        records.append(dict(id=frame['id'],partition=frame['partition'],session=frame['session'],
                            group=frame['group'],variant=path+'__without_'+family,path=path,omitted_loss_family=family,
                            base_family=frame['selected_family'],new_family=choice['family'],
                            base_candidate_id=frame['selected_candidate_id'],new_candidate_id=choice['candidate_id'],
                            family_changed=choice['family']!=frame['selected_family'],
                            candidate_changed=choice['candidate_id']!=frame['selected_candidate_id'],
                            base_success=base_good,new_success=new_good,transition=transition,
                            base_translation_cm=float(row['translation_cm']) if row['translation_cm'] else None,
                            base_rotation_deg=float(row['rotation_deg']) if row['rotation_deg'] else None,
                            new_translation_cm=score['translation_cm'],new_rotation_deg=score['rotation_deg'],
                            cached_G13_reuse=choice['cached_G13_reuse'],
                            original_hard_guards_and_correspondences_preserved=True))
        variants=[path+'__without_'+family for path in protocol['paths'] for family in protocol['actual_additive_families']]
        summary=[summarize(records,cohort,variant) for cohort in ('PRIMARY','TEST','REMAINDER','CAL') for variant in variants]
        save_rows(output/'SCORE_INFLUENCE_ROWS.jsonl.gz',records)
        write_csv(output/'SCORE_INFLUENCE_DIAGNOSTIC.csv',[dict(cohort=s['cohort'],variant=s['variant'],N=s['N'],
            success=s['new_success'],base_success=s['base_success'],recovery=s['recovery'],damage=s['damage'],
            both_success=s['both_success'],both_failure=s['both_failure'],
            translation_mean_cm=s['continuous']['translation_cm']['mean'],translation_SD_cm=s['continuous']['translation_cm']['SD'],
            translation_max_cm=s['continuous']['translation_cm']['max'],rotation_mean_deg=s['continuous']['rotation_deg']['mean'],
            rotation_SD_deg=s['continuous']['rotation_deg']['SD'],rotation_max_deg=s['continuous']['rotation_deg']['max'],
            translation_delta_cm=s['paired_delta']['translation_cm']['mean_delta'],rotation_delta_deg=s['paired_delta']['rotation_deg']['mean_delta']) for s in summary])
        write(output/'INFLUENCE_SUMMARY.json',dict(summary=summary,disclaimer=DISCLAIMER,
            predeclared_variants=variants,all_238_rows_per_variant=len(records)==238*6,
            original_selection_without_omission_exact=len(replay)==238*2,
            source_protocol_sha256=sha(root/'INFLUENCE_PROTOCOL.json'),runtime_guard=guard.receipt(),
            ranking_outcomes_not_new_method_validation=True))
        write(output/'INFLUENCE_SEAL.json',dict(artifacts={p.name:sha(p) for p in sorted(output.iterdir())},
            original_selection_replay_sha256=sha(root/'selection_v1/SELECTION_SEAL.json'),
            cost_seal_sha256=sha(root/'cost_v1/COST_SEAL.json'),metric_check_sha256=sha(root/'metrics_v2/METRIC_CHECK.json')))
    return summary


