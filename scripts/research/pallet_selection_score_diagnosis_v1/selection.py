"""Replay only discrete selections of already saved G10/G13/e records.

No original solver is invoked or imported.  The numerical operation used for
deduplication is the original fixed-pose relative rotation predicate.
"""
from __future__ import annotations

import argparse
from collections import Counter
from copy import deepcopy
from pathlib import Path
import time

import numpy as np
from scipy.spatial.transform import Rotation

from .bank import FAMILIES, STAGES, group_for_oracle, input_rows, retained_record, save_rows, sha, write

ATOL = 1e-9


def assert_numeric_equal(expected, actual, label, issues):
    if expected is None or actual is None:
        if expected is not actual:
            issues.append(dict(label=label, reason="missing_numeric_value"))
        return
    a, b = np.asarray(expected, dtype=float), np.asarray(actual, dtype=float)
    if a.shape != b.shape or not np.isfinite(a).all() or not np.isfinite(b).all() or not np.allclose(a, b, atol=ATOL, rtol=0):
        issues.append(dict(label=label, reason="numeric_mismatch", atol=ATOL, rtol=0,
                           maximum_absolute_difference=None if a.shape != b.shape else float(np.max(np.abs(a-b)))))


def same_pose(first, second, scale):
    """Exact copied predicate from joint_ot_pnp._same_pose, not a pose fit."""
    angle = Rotation.from_matrix(np.asarray(first["R"]) @ np.asarray(second["R"]).T).magnitude()
    return bool(angle < 1e-5 and np.linalg.norm(np.asarray(first["t"])-second["t"]) / scale < 1e-5)


def comparator(record, schema):
    """U parent reuse preserves stable objective-only parent order."""
    objective = record.get("objective", record.get("original_record", {}).get("objective"))
    name = record.get("initialization", record.get("original_record", {}).get("initialization", ""))
    return (objective,) if schema == "statewise_u_region_solver_v4_5" else (objective, name)


def discrete_family_choice(families):
    eligible = [(index, f) for index, f in enumerate(families) if f["accepted"]]
    return min(eligible, key=lambda item: (item[1]["original_objective"], item[0]))[0] if eligible else 0


def rank_retained(candidates, score_by_id=None):
    """Rank an unchanged eligible pool with its original stable comparator.

    Optional fixed scalar scores support the predeclared one-loss-family
    influence diagnosis. This does not modify hard validity, dedup, family,
    candidate registration, or pose. It deliberately refuses mixed packages.
    """
    values = list(candidates)
    if not values:
        return []
    package = {(c["id"], c["stage"], c["family"], c["solver_schema"]) for c in values}
    if len(package) != 1 or not all(c["retained"] for c in values):
        raise ValueError("A single unchanged frame/stage/family retained pool required")
    if score_by_id is not None and set(score_by_id) != {c["candidate_id"] for c in values}:
        raise ValueError("Exactly one fixed score for every retained candidate required")
    # The serialized samples were already ordered by the original comparator.
    # Restore pre-sort insertion order to retain stable behavior on exact ties.
    values.sort(key=lambda c:c["original_outcome_order"])
    def key(c):
        value = c["original_record"]["objective"] if score_by_id is None else score_by_id[c["candidate_id"]]
        if not np.isfinite(value):
            raise ValueError("Finite scalar score required")
        return ((value,) if c["solver_schema"] == "statewise_u_region_solver_v4_5"
                else (value, c["original_record"]["initialization"]))
    return sorted(values, key=key)


def _endpoint_sequence(family, stage, endpoints, *, cached_g13):
    schema = family["solver_schema"]
    if "outline_solver" in schema:
        source_stage = "G10" if stage == "G13" and cached_g13 else stage
        result = [deepcopy(e["original_endpoint_record"]) | {"R": e["R"], "t": e["t"]}
                  for e in endpoints if e["stage"] == source_stage and e["family"] == family["name"]
                  and e["kind"] == "outline_consider"]
        return result, "sealed_original_consumer_outline_endpoints"
    # Delegated saved solvers retain their own original finite outcome ledger.
    # Reading these records does not claim they were newly generated by e.
    return [deepcopy(v["original_record"]) for v in family["original_outcomes"]], "original_backend_outcome_records"


def replay_family(index, original, stage, family, endpoints, oracle, *, cached_g13=False):
    issues, sequence_audit, kept = [], [], []
    records, endpoint_scope = _endpoint_sequence(family, stage, endpoints, cached_g13=cached_g13)
    scale = max(float(np.linalg.norm(np.ptp(family["native_xyz"], axis=0))), 1e-3)
    source_outcomes = [x["original_record"] for x in family["original_outcomes"]]
    if "outline_solver" in family["solver_schema"]:
        expected_numeric = [v for v in source_outcomes if "error" not in v]
        if len(expected_numeric) != len(records):
            issues.append(dict(label="endpoint_sequence_length", expected=len(expected_numeric), actual=len(records)))
        for number, (source, replay) in enumerate(zip(expected_numeric, records)):
            for key in ("initialization", "branch", "joint_feasible", "optimizer_success"):
                if source.get(key) != replay.get(key) or type(source.get(key)) is not type(replay.get(key)):
                    issues.append(dict(label=f"endpoint/{number}/{key}", reason="exact_value_or_type"))
            for key in ("objective", "minimum_constraint_slack"):
                assert_numeric_equal(source.get(key), replay.get(key), f"endpoint/{number}/{key}", issues)
    for order, record in enumerate(records):
        joint = record.get("joint_feasible") is True
        valid_outline = (record.get("objective_components", {}).get("global_outline_audit", {}).get("valid_projection") is True
                         if "outline_solver" in family["solver_schema"] else True)
        has_pose = record.get("R") is not None and record.get("t") is not None
        representative = (next((s for s in kept if same_pose(record, s[1], scale)), None)
                          if joint and valid_outline and has_pose else None)
        accepted = bool(joint and valid_outline and has_pose and representative is None)
        sequence_audit.append(dict(original_outcome_order=order, initialization=record.get("initialization"),
            branch=record.get("branch"), joint_feasible=joint, valid_outline=valid_outline,
            pose_available=has_pose, retained_by_original_dedup=accepted,
            dedup_representative_outcome_order=None if representative is None else representative[0],
            objective=record.get("objective")))
        if accepted:
            kept.append((order, record))
    kept.sort(key=lambda entry: comparator(entry[1], family["solver_schema"]))
    expected = family["feasible_samples"]
    if len(kept) != len(expected):
        issues.append(dict(label="retained_count", expected=len(expected), actual=len(kept)))
    candidates = []
    for rank, (sample, retained) in enumerate(zip(expected, kept)):
        record, source = sample["original_record"], retained[1]
        for key in ("R", "t", "objective"):
            assert_numeric_equal(record[key], source[key], f"retained/{rank}/{key}", issues)
        if record["initialization"] != source["initialization"]:
            issues.append(dict(label=f"retained/{rank}/initialization", reason="exact_name_order"))
        candidate = retained_record(index, original, stage, family, sample, source, oracle)
        candidate["original_outcome_order"] = retained[0]
        candidate["original_branch"] = source.get("branch")
        candidate["original_comparator"] = "stable objective" if family["solver_schema"] == "statewise_u_region_solver_v4_5" else "(objective, initialization), stable on exact ties"
        candidate["selected_family_winner"] = family["accepted"] and rank == 0
        candidates.append(candidate)
    # No missing sample is omitted even when replay cannot establish eligibility.
    for sample in expected[len(candidates):]:
        candidate = retained_record(index, original, stage, family, sample, {}, oracle)
        candidate["selection_replay_unresolved"] = True
        candidate["selected_family_winner"] = False
        candidates.append(candidate)
    chosen = kept[0][1] if kept else None
    if family["accepted"]:
        if chosen is None:
            issues.append(dict(label="accepted_winner", reason="no_eligible_candidate"))
        else:
            for key, field in (("R_cf", "R"), ("native_t", "t")):
                assert_numeric_equal(family["selected_solver_pose"][key], chosen[field], "winner/"+field, issues)
            assert_numeric_equal(family["original_objective"], chosen["objective"], "winner/objective", issues)
    elif kept:
        issues.append(dict(label="unaccepted_has_eligible_candidate", count=len(kept)))
    published = family["published_actual_pose"]
    if published is not None:
        expected_pose = family["selected_solver_pose"]
        if family["accepted"] and expected_pose is not None:
            for key in ("R_cf", "centroid", "R_physical"):
                assert_numeric_equal(expected_pose[key], published[key], "published/"+key, issues)
        if published.get("physical_registration_Q") is not None:
            assert_numeric_equal(family["physical_registration_Q"], published["physical_registration_Q"], "published/Q", issues)
        if published.get("R_cf") is not None and published.get("R_physical") is not None:
            assert_numeric_equal(np.asarray(published["R_cf"]) @ family["physical_registration_Q"], published["R_physical"], "published/physical_R", issues)
    return dict(stage=stage, family=family["name"], solver_schema=family["solver_schema"],
        accepted=family["accepted"], fallback=not family["accepted"], status=family["solver_status"],
        winner_candidate_id=candidates[0]["candidate_id"] if family["accepted"] and candidates else None,
        original_objective=family["original_objective"], retained_count=len(expected),
        recomputed_retained_count=len(kept), endpoint_scope=endpoint_scope,
        source_outcome_count=len(source_outcomes), endpoint_count=len(records),
        original_search=family.get("original_search"), sequence_audit=sequence_audit,
        published_actual_pose=deepcopy(published), published_fallback_audit=deepcopy(family["published_fallback_audit"]),
        passed=not issues, issues=issues), candidates


def replay_frame(index, original, endpoints, oracle):
    group = group_for_oracle(oracle)
    stages, all_candidates, issues = {}, [], []
    cached_g13 = original["original_source"]["exact_D_G10_cache_reuse"] is True
    for stage in STAGES:
        families = original["stages"][stage]["families"]
        if [f["name"] for f in families] != list(FAMILIES):
            raise ValueError("Exact original family order required")
        families_audit = []
        for family in families:
            audit, candidates = replay_family(index, original, stage, family, endpoints, oracle, cached_g13=cached_g13)
            families_audit.append(audit); all_candidates.extend(candidates)
            if not audit["passed"]:
                issues.append(dict(stage=stage, family=family["name"], issues=audit["issues"]))
        choice = discrete_family_choice(families)
        if original["stages"][stage]["selected_family"] != FAMILIES[choice]:
            issues.append(dict(stage=stage, reason="family_selection_mismatch"))
        stages[stage] = dict(selected_family=FAMILIES[choice], selected_family_index=choice,
                             families=families_audit, exact_tie_rule="ORIGINAL_WD first")
    frozen = stages["G10"]["selected_family"]
    chosen = stages["G13"]["families"][FAMILIES.index(frozen)]
    if original["original_e"]["frozen_family"] != frozen:
        issues.append(dict(reason="e_frozen_family_mismatch"))
    if original["original_e"]["accepted"] is not chosen["accepted"]:
        issues.append(dict(reason="e_accepted_mismatch"))
    epose = original["original_e"]["actual_pose"]
    for key in ("R_cf", "centroid", "R_physical", "physical_registration_Q", "cf_extents"):
        assert_numeric_equal(epose[key], chosen["published_actual_pose"][key], "e/"+key, issues)
    for key in ("source", "available", "joint_feasible", "fallback", "fallback_pose_does_not_solve_OT"):
        if epose.get(key) != chosen["published_actual_pose"].get(key) or type(epose.get(key)) is not type(chosen["published_actual_pose"].get(key)):
            issues.append(dict(reason="e_exact_pose_metadata_mismatch", field=key))
    selected_candidates = [c for c in all_candidates if c["stage"] == "G13" and c["family"] == frozen]
    all_g13 = [c for c in all_candidates if c["stage"] == "G13"]
    successes = [c for c in selected_candidates if c["reference_success"]]
    failures = [c for c in selected_candidates if not c["reference_success"]]
    all_successes = [c for c in all_g13 if c["reference_success"]]
    # Per-family arrays retain their original comparator order. Cross-family
    # representative uses the actual G13 family comparator, not GT proximity.
    all_successes.sort(key=lambda c: (c["original_record"]["objective"], FAMILIES.index(c["family"]),
                                      c["original_record"]["initialization"], c["source_order"]))
    representative_good = successes[0] if successes else all_successes[0] if all_successes else None
    representative_bad = failures[0] if failures else None
    frame = dict(id=original["id"], index=index, partition=original["partition"], session=original["session"],
        image_sha256=original["image_sha256"], states=original["states"], group=group,
        selected_family=frozen, g13_reselected_family=stages["G13"]["selected_family"],
        selected_candidate_id=chosen["winner_candidate_id"], stages=stages,
        stage_winner_ids={s:{f["family"]:f["winner_candidate_id"] for f in stages[s]["families"]} for s in STAGES},
        reference_success_candidates_g13_selected_family=[c["candidate_id"] for c in successes],
        reference_success_candidates_g13_all=[c["candidate_id"] for c in all_successes],
        representative_success_candidate_id=None if representative_good is None else representative_good["candidate_id"],
        representative_failure_candidate_id=None if representative_bad is None else representative_bad["candidate_id"],
        original_e_actual_pose=deepcopy(epose), original_e_accepted=original["original_e"]["accepted"],
        original_e_fallback_audit=deepcopy(original["original_e"]["fallback_audit"]),
        original_e_hierarchy=deepcopy(original["original_e"]["hierarchy"]),
        final_reference_success=oracle["final_joint_success"],
        g10_reference_success_candidate_ids=oracle["original_stage_oracles"]["G10"]["feasible"]["joint_success_candidate_ids"],
        cached_g13_no_typed_revocation=cached_g13,
        selection_replay_status="PASS" if not issues else "SELECTION_REPLAY_UNRESOLVED", issues=issues)
    by_id = {c["candidate_id"]:c for c in all_candidates}
    def good(cid):
        return None if cid is None else by_id[cid]["reference_success"]
    opposite = FAMILIES[1-FAMILIES.index(frozen)]
    frame["family_reference_diagnosis"] = dict(
        G10_retained_success_exists=bool(frame["g10_reference_success_candidate_ids"]),
        G10_frozen_family_winner_success=good(frame["stage_winner_ids"]["G10"][frozen]),
        G10_opposite_family_winner_success=good(frame["stage_winner_ids"]["G10"][opposite]),
        G13_opposite_family_winner_success=good(frame["stage_winner_ids"]["G13"][opposite]),
        G13_own_family_reselector_success=good(frame["stage_winner_ids"]["G13"][frame["g13_reselected_family"]]),
        G13_success_only_without_G10_success=bool(all_successes and not frame["g10_reference_success_candidate_ids"]),
        these_are_reference_diagnostics_not_input_to_original_selection=True)
    pairs = []
    for stage in STAGES:
        accepted = [f for f in stages[stage]["families"] if f["accepted"]]
        if len(accepted) == 2:
            s = next(f for f in accepted if f["family"] == stages[stage]["selected_family"])
            other = next(f for f in accepted if f["family"] != s["family"])
            pairs.append(dict(id=frame["id"], partition=frame["partition"], group=group, stage=stage,
                family=s["family"], other_family=other["family"], s_candidate_id=s["winner_candidate_id"],
                other_candidate_id=other["winner_candidate_id"], pair_role="accepted_family_winner_comparison",
                same_objective_package=True, family_specific_geometry_and_observations=True))
    if chosen["winner_candidate_id"] is not None:
        if group == "WITHIN_FAMILY_SELECTION_LOSS" and representative_good is not None:
            pairs.append(dict(id=frame["id"], partition=frame["partition"], group=group, stage="G13", family=frozen,
                s_candidate_id=chosen["winner_candidate_id"], other_candidate_id=representative_good["candidate_id"],
                pair_role="selected_vs_comparator_first_reference_success_same_family", same_objective_package=True))
        if group == "FINAL_SUCCESS_CONTROL" and representative_bad is not None:
            pairs.append(dict(id=frame["id"], partition=frame["partition"], group=group, stage="G13", family=frozen,
                s_candidate_id=chosen["winner_candidate_id"], other_candidate_id=representative_bad["candidate_id"],
                pair_role="selected_vs_comparator_first_reference_failure_same_family", same_objective_package=True))
    return frame, all_candidates, pairs


def run(old_root, output):
    started, cpu = time.monotonic(), time.process_time()
    output = Path(output)
    if output.exists():
        raise FileExistsError("Preserve previous selection attempts")
    output.mkdir(parents=True)
    frames, candidates, pairs = [], [], []
    for index, original, endpoints, oracle in input_rows(old_root):
        frame, values, frame_pairs = replay_frame(index, original, endpoints, oracle)
        frames.append(frame); candidates.extend(values); pairs.extend(frame_pairs)
    counts = {partition: dict(Counter(f["group"] for f in frames if f["partition"] == partition))
              for partition in ("CAL", "TEST", "REMAINDER")}
    counts["PRIMARY"] = dict(Counter(f["group"] for f in frames if f["partition"] != "CAL"))
    expected = dict(FINAL_SUCCESS_CONTROL=114, FAMILY_SELECTION_LOSS=10,
                    WITHIN_FAMILY_SELECTION_LOSS=22, NO_SUCCESS_CANDIDATE=46)
    if counts["PRIMARY"] != expected:
        raise ValueError("Original PRIMARY group counts differ: " + str(counts["PRIMARY"]))
    if counts["CAL"] != dict(FINAL_SUCCESS_CONTROL=37, FAMILY_SELECTION_LOSS=3, NO_SUCCESS_CANDIDATE=6):
        raise ValueError("Original CAL group counts differ")
    summary = dict(schema="FIXED_RECORD_SELECTION_REPLAY_V1", rows=len(frames),
        all_passed=all(f["selection_replay_status"] == "PASS" for f in frames),
        passed_rows=sum(f["selection_replay_status"] == "PASS" for f in frames),
        unresolved_ids=[f["id"] for f in frames if f["selection_replay_status"] != "PASS"],
        group_counts=counts, retained_candidate_records=len(candidates),
        retained_by_stage=dict(Counter(c["stage"] for c in candidates)),
        comparator_pairs=len(pairs), atol=ATOL, rtol=0,
        controls_with_eligible_bad={p:sum(f["group"] == "FINAL_SUCCESS_CONTROL" and
            f["representative_failure_candidate_id"] is not None for f in frames
            if (f["partition"] != "CAL" if p == "PRIMARY" else f["partition"] == p))
            for p in ("PRIMARY", "CAL", "TEST", "REMAINDER")},
        family_loss_reference_counts={p:{key:sum(f["family_reference_diagnosis"][key] is True
            for f in frames if f["group"] == "FAMILY_SELECTION_LOSS" and
            (f["partition"] != "CAL" if p == "PRIMARY" else f["partition"] == p))
            for key in ("G10_retained_success_exists", "G10_frozen_family_winner_success",
                "G10_opposite_family_winner_success", "G13_opposite_family_winner_success",
                "G13_own_family_reselector_success", "G13_success_only_without_G10_success")}
            for p in ("PRIMARY", "CAL", "TEST", "REMAINDER")},
        source_hashes={str(p):sha(p) for p in (Path(__file__), Path(__file__).with_name("bank.py"))},
        new_learning_updates=0, new_model_forwards=0, new_PnP_calls=0, new_optimizers=0,
        new_candidate_generation_calls=0,
        elapsed_seconds=time.monotonic()-started, worker_cpu_seconds=time.process_time()-cpu)
    save_rows(output/"FRAME_SELECTIONS.jsonl.gz", frames)
    save_rows(output/"RETAINED_CANDIDATES.jsonl.gz", candidates)
    save_rows(output/"PAIR_DEFINITIONS.jsonl.gz", pairs)
    write(output/"SELECTION_REPLAY.json", summary)
    write(output/"SELECTION_SEAL.json", dict(schema="SELECTION_RECORD_ANALYSIS_SEAL_V1", rows=238,
        artifacts={p.name:sha(p) for p in sorted(output.iterdir())}, original_result_commit="407de865445e4987614f50f893d2ccea78d507b6",
        final_selection_reproduced=summary["all_passed"], records_only=True))
    return summary


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--old-root", required=True, type=Path)
    parser.add_argument("--output", required=True, type=Path)
    args = parser.parse_args()
    result = run(args.old_root, args.output)
    print({k:result[k] for k in ("rows", "all_passed", "passed_rows", "group_counts", "retained_candidate_records", "elapsed_seconds")})
