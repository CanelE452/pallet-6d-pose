def guard(args, stage):
    for path in (args.input, args.output, args.protocol, args.parent, args.point_parent, args.cohort):
        path = path.absolute()
        require(not any(p.is_symlink() for p in (path, *path.parents)), 'symlink input/output ancestry')
    output = args.output.resolve()
    require(output == DOC.resolve() or output.is_relative_to(PRIVATE.resolve()), 'only new V9 DOC/private audit output')
    require(all(path.is_dir() for path in (args.input, args.output, args.parent, args.point_parent)), 'existing directories required')
    for name in OUTPUTS if stage == 'freeze' else OUTPUTS[1:]:
        require(not (output/name).exists(), 'preserve existing ' + name)
    if stage == 'run':
        require((output/OUTPUTS[0]).is_file(), 'own freeze required before arithmetic')
    return args.input.resolve(), output


