def rows(path):
    with gzip.open(path, 'rt', encoding='utf-8') as stream:
        for line in stream:
            require(bool(line.strip()), 'empty stored JSONL row')
            yield json.loads(line)


def binding(path):
    path = Path(path).absolute()
    require(path.is_file() and not any(p.is_symlink() for p in (path, *path.parents)), 'missing/symlink input ' + str(path))
    digest = hashlib.sha256()
    with path.open('rb') as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b''):
            digest.update(block)
    path = path.resolve()
    return dict(path=str(path.relative_to(REPO)) if path.is_relative_to(REPO) else path.name,
                bytes=path.stat().st_size, sha256=digest.hexdigest())


def same_binding(a, b):
    return isinstance(a, dict) and isinstance(b, dict) and all(a.get(k) == b.get(k) for k in ('bytes', 'sha256'))


def semantic(value):
    return hashlib.sha256(json.dumps(value, sort_keys=True, separators=(',', ':'), allow_nan=False).encode()).hexdigest()


def safe(value):
    if isinstance(value, dict):
        return {str(k): safe(v) for k, v in value.items()}
    if isinstance(value, (set, frozenset)):
        return sorted([safe(v) for v in value], key=lambda v: json.dumps(v, sort_keys=True))
    if isinstance(value, (list, tuple)):
        return [safe(v) for v in value]
    return repr(value) if isinstance(value, float) and not math.isfinite(value) else value


def write_new(path, value):
    with Path(path).open('x', encoding='utf-8') as stream:
        json.dump(safe(value), stream, ensure_ascii=False, indent=2, allow_nan=False)
        stream.write('\n'); stream.flush(); os.fsync(stream.fileno())


class Audit:
    def __init__(self):
        self.checks, self.failure_count, self.max_difference = 0, 0, 0.
        self.failures = []

    def ok(self, value, label, actual=None, expected=None):
        self.checks += 1
        if not value:
            self.failure_count += 1
            if len(self.failures) < 100:
                self.failures.append(dict(check=label, actual=safe(actual), expected=safe(expected)))

    def eq(self, actual, expected, label):
        self.ok(actual == expected, label, actual, expected)

    def near(self, actual, expected, label):
        if isinstance(expected, dict):
            valid = isinstance(actual, dict) and set(actual) == set(expected)
            self.ok(valid, label + '.fields', actual, expected)
            if valid:
                for k in expected:
                    self.near(actual[k], expected[k], label + '.' + k)
        elif isinstance(expected, (list, tuple)):
            valid = isinstance(actual, (list, tuple)) and len(actual) == len(expected)
            self.ok(valid, label + '.shape', actual, expected)
            if valid:
                for i, (a, e) in enumerate(zip(actual, expected)):
                    self.near(a, e, label + '.' + str(i))
        elif type(expected) in (int, float):
            valid = type(actual) in (int, float) and math.isfinite(actual) and math.isfinite(expected)
            d = abs(actual-expected) if valid else None
            if d is not None:
                self.max_difference = max(self.max_difference, d)
            self.ok(valid and d <= ATOL+RTOL*abs(expected), label, actual, expected)
        else:
            self.eq(actual, expected, label)


def finite(value, shape=()):
    if not shape:
        return type(value) in (int, float) and math.isfinite(value)
    return isinstance(value, (list, tuple)) and len(value) == shape[0] and all(finite(v, shape[1:]) for v in value)


def dot(a, b):
    return math.fsum(x*y for x, y in zip(a, b))


def mm(a, b):
    return [[dot(row, column) for column in zip(*b)] for row in a]


def eye():
    return [[float(i == j) for j in range(3)] for i in range(3)]


def skew(v):
    x, y, z = v
    return [[0., -z, y], [z, 0., -x], [-y, x, 0.]]


def rotation_and_right_J(r):
    require(finite(r, (3,)), 'nonfinite rotation vector')
    theta2 = dot(r, r)
    theta = math.sqrt(theta2)
    if theta < 1e-5:
        A = 1-theta2/6+theta2*theta2/120
        B = .5-theta2/24+theta2*theta2/720
        C = 1/6-theta2/120+theta2*theta2/5040
    else:
        A, B, C = math.sin(theta)/theta, (1-math.cos(theta))/theta2, (theta-math.sin(theta))/(theta2*theta)
    W, I = skew(r), eye()
    W2 = mm(W, W)
    R = [[I[i][j]+A*W[i][j]+B*W2[i][j] for j in range(3)] for i in range(3)]
    right = [[I[i][j]-B*W[i][j]+C*W2[i][j] for j in range(3)] for i in range(3)]
    return R, right


def dimensions(xyz):
    return [xyz] if abs(xyz[0]-xyz[2]) < 1e-9 else [xyz, [xyz[2], xyz[1], xyz[0]]]


def model(extents):
    a, b, c = [v/2 for v in extents]
    return [(-a, -b, -c), (a, -b, -c), (a, b, -c), (-a, b, -c),
            (-a, -b, c), (a, -b, c), (a, b, c), (-a, b, c)]


def forward(extents, z, K):
    require(finite(z, (6,)) and finite(extents, (3,)) and finite(K, (3, 3)), 'invalid scalar forward input')
    R, right = rotation_and_right_J(z[:3])
    uv, jac, depths = [], [], []
    for p in model(extents):
        camera = [dot(row, p)+t for row, t in zip(R, z[3:])]
        denominator = dot(K[2], camera)
        require(camera[2] > 1e-9 and denominator > 0, 'nonpositive candidate depth')
        numerator = [dot(row, camera) for row in K[:2]]
        uv.append([v/denominator for v in numerator]); depths.append(camera[2])
        dr = [[-v for v in row] for row in mm(mm(R, skew(p)), right)]
        dc = [row+identity for row, identity in zip(dr, eye())]
        perspective = [[(K[axis][j]*denominator-numerator[axis]*K[2][j])/(denominator*denominator)
                        for j in range(3)] for axis in range(2)]
        jac.append(mm(perspective, dc))
    return R, uv, jac, depths


def physical_rotation(R, dim):
    return R if dim == 0 else [[-row[2], row[1], row[0]] for row in R]


