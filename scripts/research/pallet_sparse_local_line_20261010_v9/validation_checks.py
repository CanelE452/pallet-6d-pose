def original_lines(obs, q, U, adopted, audit, label):
    corners = {int(c['id']): c for c in obs['corners']}
    require(len(corners) == len(obs['corners']), 'duplicate original corner')
    consumed = set()
    for k in adopted:
        if k not in U:
            continue
        c = corners[k]
        audit.eq(c['xy'], q[k], label + '.adopted_actual_corner.' + str(k))
        edges = c['edges']
        require(len(edges) == len(set(edges)) == 2 and all(type(e) is int and e in PHYSICAL and k in EDGES[e] for e in edges),
                'invalid physically supported adopted incident edges')
        consumed.update(edges)
    seen, accepted = {}, []
    for raw in obs['lines']:
        edge = raw['edge']
        require(type(edge) is int and 0 <= edge < 12, 'invalid original edge')
        identity = json.dumps(raw, sort_keys=True, separators=(',', ':'), allow_nan=False)
        if edge in seen:
            require(seen[edge] == identity, 'inconsistent original duplicate edge')
            continue
        seen[edge] = identity
        audit.eq(raw['endpoints'], list(EDGES[edge]), label + '.endpoint_identity.' + str(edge))
        if edge not in PHYSICAL:
            require(edge not in consumed, 'consumed unsupported edge')
            continue
        normal, support, radii, queries = raw['normal'], raw['support_points'], raw['query_radii_px'], raw['queries']
        require(finite(normal, (2,)) and math.hypot(*normal) > 0 and
            finite(support, (len(queries), 2)) and finite(radii, (len(queries),)) and
            min(radii) >= 0 and len(set(queries)) >= 3 and all(type(v) is int and 0 <= v < 84 and v//7 == edge for v in queries),
            'invalid original line support')
        audit.ok(edge in CAL, label + '.source_CAL_edge.' + str(edge), edge, CAL)
        for query, xy in zip(queries, support):
            audit.eq(obs['queries'][query]['calibrated_model_coverage'], True, label + '.query_CAL.' + str(query))
            audit.eq(obs['queries'][query]['selected_xy'], xy, label + '.sealed_support.' + str(query))
        length = math.hypot(*normal)
        n, offset = [v/length for v in normal], raw['offset']/length
        errors = [abs(dot(n, xy)-offset) for xy in support]
        good = math.isfinite(offset) and all(e <= r+1e-9 for e, r in zip(errors, radii))
        require(edge not in consumed or good, 'inconsistent consumed support line')
        if good and edge not in consumed:
            accepted.append(dict(edge=edge, normal=n, offset=offset, support_query_ids=queries))
    require(consumed <= set(seen), 'missing adopted supporting line')
    return sorted(accepted, key=lambda l: l['edge']), sorted(consumed)


