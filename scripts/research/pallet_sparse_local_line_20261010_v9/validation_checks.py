def population_stream(path, field, names, primary, total, cohort, audit, label):
    seen, counts = set(), Counter()
    for row in rows(path):
        key = (row[field], row['id'])
        require(row[field] in names and row['id'] in cohort and key not in seen, label + ': unknown/duplicate population row')
        audit.ok(not TRUTH.intersection(row), label + '.GT_free.' + row[field])
        seen.add(key); counts[row[field]] += 1
        if row[field] == primary:
            yield row
    audit.eq(len(seen), total, label + '.full_population_count')
    for name in names:
        audit.eq(counts[name], 245, label + '.per_method245.' + name)
        audit.eq({fid for method, fid in seen if method == name}, cohort, label + '.same_cohort.' + name)


def fixed_population(path, cohort, audit):
    seen, counts = set(), Counter()
    for row in rows(path):
        key = (row['method'], row['id'])
        require(row['method'] in ('BASE', 'N3_SUBPIX') and row['id'] in cohort and key not in seen, 'unknown fixed parent population')
        audit.ok(not TRUTH.intersection(row), 'fixed_parent.GT_free')
        seen.add(key); counts[row['method']] += 1
    audit.eq(len(seen), 490, 'fixed_parent.complete490')
    audit.eq(dict(counts), dict(BASE=245, N3_SUBPIX=245), 'fixed_parent.each245')


