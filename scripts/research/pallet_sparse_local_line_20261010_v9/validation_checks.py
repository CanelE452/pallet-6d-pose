def run(args):
    _, output = guard(args, 'run')
    paths = input_paths(args); own_path = output/OUTPUTS[0]
    own = read(own_path); own_binding = binding(own_path)
    inputs = {k: binding(p) for k, p in paths.items()}
    require(own['schema'] == 'supplemental_sparse_local_point_line_scalar_protocol_v9' and
        own['inputs'] == inputs and own['checker'] == inputs['checker'] and own['methods'] == [METHOD] and
        own['frames'] == own['rows'] == own['ledger_rows'] == 245 and own['limits'] == LIMITS and
        own['scalar_absolute_tolerance'] == ATOL and own['scalar_relative_tolerance'] == RTOL and
        own['rank_relative_threshold'] == RANK and own['objective_tie_px2'] == TIE, 'own frozen protocol differs before arithmetic')
    core, seal, receipt, population = bound_receipts(paths, inputs)
    write_new(output/OUTPUTS[1], dict(schema='supplemental_sparse_local_point_line_scalar_started_v9',
        own_protocol=own_binding, inputs=inputs, checker=inputs['checker'], new_production_calls=0,
        GT_image_model_optimizer_calls=0, automatic_retry=False))
    audit, counts, failure = Audit(), Counter(), None
    began = time.monotonic()
    try:
        cohort = read(paths['cohort'])
        audit.eq(cohort['counts'], dict(clean=153, moderate=92, severe_excluded=74, original=319), 'cohort.easy_moderate_only')
        ordered, known = cohort['ids'], set(cohort['ids'])
        require(len(ordered) == len(known) == 245 and [f['id'] for f in cohort['frames']] == ordered, 'cohort order/population differs')
        audit.ok(all(f['label'] in ('clean', 'moderate') for f in cohort['frames']), 'cohort.no_severe')
        audit.ok(not known & set(cohort['excluded_ids']) and len(set(cohort['excluded_ids'])) == 74, 'cohort.excluded74')
        parent = iter(population_stream(paths['parent:GEOMETRY_SEALED.jsonl.gz'], 'method', PARENT_METHODS,
            'IMAGE_ROLE_BOUNDARY_ONLY', 1960, known, audit, 'parent_geometry'))
        obs = iter(population_stream(paths['parent:OBSERVATIONS.jsonl.gz'], 'head_arm', HEADS, 'IMAGE_ROLE', 735, known, audit, 'parent_observation'))
        point = iter(population_stream(paths['point:GEOMETRY_SEALED.jsonl.gz'], 'method', POINT_METHODS, POINT_METHODS[0], 735, known, audit, 'point_controls'))
        new, ledgers = iter(rows(paths['geometry'])), iter(rows(paths['ledgers']))
        for i, frame_id in enumerate(ordered):
            group = [next(stream, None) for stream in (new, ledgers, parent, obs, point)]
            require(all(isinstance(row, dict) for row in group), 'incomplete joined frame group')
            row, ledger, p, o, control = group
            require(all(r['id'] == frame_id and r['session'] == p['session'] for r in group), 'joined frame order/session differs')
            audit.eq(row['session'], cohort['frames'][i]['session'], 'cohort.frame_session.' + str(i))
            audit.ok(not TRUTH.intersection(row) and not TRUTH.intersection(o), 'frame.GT_free.' + str(i))
            audit.eq(ledger['schema'], 'same_sparse_ROLE_local_point_line_ledger_v9', 'frame.ledger_schema.' + str(i))
            packet(row, ledger, p, o, control, audit, counts, 'frame.' + str(i))
        for name, stream in (('local_geometry', new), ('local_ledgers', ledgers), ('parent_geometry', parent), ('parent_observation', obs), ('point_controls', point)):
            audit.eq(next(stream, None), None, name + '.no_extra_population')
        fixed_population(paths['parent:FIXED_GEOMETRY_SEALED.jsonl.gz'], known, audit)
        recorded_receipts(paths, inputs, core, seal, receipt, population, counts, audit)
        audit.eq(counts['local_packets'], 245, 'complete.local245')
        audit.eq({k: binding(p) for k, p in paths.items()}, inputs, 'complete.all_input_bytes_unchanged_after_arithmetic')
        audit.eq(binding(own_path), own_binding, 'complete.own_protocol_unchanged_after_arithmetic')
    except BaseException as error:
        failure = dict(type=type(error).__name__, message=str(error))
    complete = failure is None and counts['local_packets'] == 245
    passed = complete and audit.failure_count == 0
    write_new(output/OUTPUTS[2], dict(schema='supplemental_sparse_local_point_line_scalar_checks_v9',
        complete=complete, passed=passed, own_protocol=own_binding, checker=inputs['checker'], inputs=inputs,
        limits=LIMITS, checks=audit.checks, failure_count=audit.failure_count, failures=audit.failures,
        exception=failure, counts=dict(counts), max_scalar_absolute_difference=audit.max_difference,
        wall_seconds=time.monotonic()-began, new_model_GT_image_optimizer_PnP_SVD_calls=0,
        full_candidate_witnesses_retained_in_original_geometry=True, full_population_rows_retained=0,
        original_geometry_unchanged=True if passed else 'checked only if reached final binding comparison',
        first_failure_preserved=True, automatic_retry=False))
    print('SPARSE_LOCAL_SCALAR', 'PASS' if passed else 'FAIL', audit.checks, dict(counts), flush=True)
    if not passed:
        raise SystemExit(1)


