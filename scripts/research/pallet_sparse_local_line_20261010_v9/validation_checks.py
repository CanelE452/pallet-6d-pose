def seed_valid(raw, dims):
    if not isinstance(raw, dict) or not raw.get('available'):
        return False
    if not all(finite(raw.get(k), shape) for k, shape in
               (('R_cf', (3, 3)), ('R_physical', (3, 3)), ('centroid', (3,)), ('cf_extents', (3,)))):
        return False
    for R in (raw['R_cf'], raw['R_physical']):
        determinant = dot(R[0], [R[1][1]*R[2][2]-R[1][2]*R[2][1],
            R[1][2]*R[2][0]-R[1][0]*R[2][2], R[1][0]*R[2][1]-R[1][1]*R[2][0]])
        if abs(determinant-1) > 1e-6 or max(abs(dot(a, b)-int(i == j)) for i, a in enumerate(R) for j, b in enumerate(R)) > 1e-6:
            return False
    matches = [i for i, d in enumerate(dims) if max(abs(a-b) for a, b in zip(raw['cf_extents'], d)) <= 1e-6]
    return len(matches) == 1 and max(abs(a-b) for row, other in zip(raw['R_physical'],
        physical_rotation(raw['R_cf'], matches[0])) for a, b in zip(row, other)) <= 1e-6


