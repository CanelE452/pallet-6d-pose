def factor_rows(uv, J, q, U, lines, modeled=False):
    residual, matrix = [], []
    for k in U:
        residual.extend([uv[k][i]-q[k][i] for i in range(2)])
        matrix.extend(J[k])
    for line in lines:
        a, b = EDGES[line['edge']]
        n = line['normal']
        if modeled:
            direction = [uv[b][i]-uv[a][i] for i in range(2)]
            length = math.hypot(*direction)
            require(length > 1e-12 and math.isfinite(length), 'projected_model_edge_degenerate')
            n = [-direction[1]/length, direction[0]/length]
        for k in (a, b):
            residual.append((dot(n, uv[k])-line['offset'])/math.sqrt(2))
            matrix.append([math.fsum(n[i]*J[k][i][j] for i in range(2))/math.sqrt(2) for j in range(6)])
    return residual, matrix


def rank_witness(w, matrix, audit, label):
    n = len(matrix)
    audit.eq(w['scalar_rows'], n, label + '.scalar_rows')
    audit.eq(w['local_only'], True, label + '.local_only')
    if not n:
        audit.eq(w['singular_values'], [], label + '.empty_singular')
        audit.eq(w['normalized_column_scale'], [], label + '.empty_scale')
        audit.eq(w['numerical_rank'], 0, label + '.empty_rank')
        audit.eq(w['condition_number'], None, label + '.empty_condition')
        return 0
    singular = w['singular_values']
    require(finite(singular, (min(n, 6),)) and all(v >= 0 for v in singular), 'invalid singular witness')
    audit.ok(all(a >= b for a, b in zip(singular, singular[1:])), label + '.descending')
    scales = [max(math.sqrt(math.fsum(row[j]**2 for row in matrix)), 1e-300) for j in range(6)]
    audit.near(w['normalized_column_scale'], scales, label + '.independent_column_norms')
    audit.eq(w['normalization'], 'unit L2 Jacobian columns', label + '.normalization')
    rank = sum(s > singular[0]*RANK for s in singular)
    audit.eq(w['numerical_rank'], rank, label + '.stored_singular_rank_recount')
    audit.near(w['condition_number'], singular[0]/singular[-1] if singular[-1] > 0 else None, label + '.condition')
    # Frobenius energy is independent of the stored singular spectrum.
    normalized_energy = math.fsum((row[j]/scales[j])**2 for row in matrix for j in range(6))
    audit.near(math.fsum(s*s for s in singular), normalized_energy, label + '.singular_frobenius_energy')
    return rank


