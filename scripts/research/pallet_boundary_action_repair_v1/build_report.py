def digest(path: Path) -> str:
    h = hashlib.sha256()
    with path.open('rb') as f:
        for block in iter(lambda: f.read(1024 * 1024), b''):
            h.update(block)
    return h.hexdigest()


def get(value: Any, *paths: str, default: Any = None) -> Any:
    """Read explicit schema aliases, preserving measured zero and False."""
    for path in paths:
        current = value
        for key in path.split('/'):
            if not isinstance(current, dict) or key not in current:
                break
            current = current[key]
        else:
            if current is not None:
                return current
    return default


def number(value: Any, digits: int = 3) -> str:
    if value is None or isinstance(value, float) and not math.isfinite(value):
        return MISSING
    if isinstance(value, bool):
        return 'true' if value else 'false'
    if isinstance(value, int):
        return str(value)
    if isinstance(value, float):
        return f'{value:.{digits}f}'
    return str(value)


def execution_attempt_summary(cost, interruption, lcost, training):
    """Separate measured technical exits, UNKNOWN interruption work and fits."""
    jobs = cost.get('root_analysis_batches')
    known_jobs = jobs if isinstance(jobs, list) else None
    failed = [row for row in known_jobs or [] if isinstance(row.get('exit_code'), int)
        and not isinstance(row['exit_code'], bool) and row['exit_code'] != 0]
    unsealed = interruption.get('unsealed_attempts')
    failed_fits = lcost.get('failed_training_attempts')
    pending = training.get('pending_arms')
    batches = lcost.get('distinct_execution_batches')
    batches = batches if isinstance(batches, list) else []
    return dict(root_timed_job_n=len(known_jobs) if known_jobs is not None else None,
        root_nonzero_exit_n=len(failed) if known_jobs is not None else None,
        root_nonzero_exit_ids=[row.get('batch_id') for row in failed],
        root_unknown_exit_n=sum(row.get('exit_code') is None for row in known_jobs) if known_jobs is not None else None,
        D1_interruption_status=interruption.get('status'),
        D1_observed_exit_code=interruption.get('observed_tool_session_exit_code'),
        D1_termination_cause=interruption.get('concrete_termination_cause'),
        D1_worker_exit_codes=interruption.get('worker_exit_codes'),
        D1_unsealed_attempt_n=len(unsealed) if isinstance(unsealed, list) else None,
        D1_partial_operations=interruption.get('interrupted_partial_operations'),
        D1_partial_CPU_seconds=interruption.get('interrupted_partial_CPU_seconds'),
        D1_exact_interrupted_parentwall_seconds=interruption.get('parent_wall_seconds'),
        D1_parent_lifetime_upper_bound_seconds=interruption.get('parent_process_lifetime_upper_bound_seconds'),
        failed_fit_n=len(failed_fits) if isinstance(failed_fits, list) else None,
        pending_arm_n=len(pending) if isinstance(pending, (list, dict)) else None,
        L_D1_15fit_batch_wall_seconds=next((row.get('wall_seconds') for row in batches
            if row.get('execution_batch_id') == 'L_D1_TRAINING15'), None),
        L_D0_3fit_whole_process_wall_seconds=next((row.get('wall_seconds') for row in batches
            if row.get('execution_batch_id') == 'L_D0_H1_TRAINING3'), None),
        all_technical_attempts_are_not_training_failures=True,
        unknown_work_not_zero=True)


