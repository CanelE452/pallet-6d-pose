def contrast(summaries: dict, before: str, after: str) -> dict:
    values = {}
    for pop in POPULATIONS:
        a = summaries.get(pop, {}).get(before, {})
        b = summaries.get(pop, {}).get(after, {})
        def delta(x: Any, y: Any) -> Any:
            return y - x if isinstance(x, (int, float)) and isinstance(y, (int, float)) else None
        values[pop] = dict(success_delta=delta(a.get('successes'), b.get('successes')),
            translation_mean_delta_cm=delta(get(a, 'translation_cm/mean'), get(b, 'translation_cm/mean')),
            rotation_mean_delta_deg=delta(get(a, 'rotation_deg/mean'), get(b, 'rotation_deg/mean')),
            T_gt50cm_delta=delta(a.get('T_gt50cm'), b.get('T_gt50cm')),
            T_gt100cm_delta=delta(a.get('T_gt100cm'), b.get('T_gt100cm')),
            R_gt45deg_delta=delta(a.get('R_gt45deg'), b.get('R_gt45deg')))
        for metric in ('translation_cm', 'rotation_deg'):
            for field in ('P90', 'P95', 'max'):
                values[pop][metric + '_' + field + '_delta'] = delta(
                    get(a, metric + '/' + field), get(b, metric + '/' + field))
    return dict(before=before, after=after, populations=values)


def classify(change: dict) -> str:
    p = get(change, 'populations/PRIMARY192', default={})
    gain = p.get('success_delta')
    if gain is None:
        return 'NOT_IDENTIFIED'
    if gain <= 0:
        return 'NO_GAIN_OR_HARM'
    checks = ('translation_mean_delta_cm', 'rotation_mean_delta_deg',
              'T_gt50cm_delta', 'T_gt100cm_delta', 'R_gt45deg_delta',
              'translation_cm_P90_delta', 'translation_cm_P95_delta', 'translation_cm_max_delta',
              'rotation_deg_P90_delta', 'rotation_deg_P95_delta', 'rotation_deg_max_delta')
    rem = get(change, 'populations/REMAINDER143', default={})
    harmful = any(p.get(k) is not None and p[k] > 0 for k in checks)
    harmful |= rem.get('success_delta') is not None and rem['success_delta'] < 0
    harmful |= any(rem.get(k) is not None and rem[k] > 0 for k in checks)
    if harmful:
        return 'GAIN_WITH_TRADEOFF'
    if any(p.get(k) is None or rem.get(k) is None for k in checks) or rem.get('success_delta') is None:
        return 'NOT_IDENTIFIED'
    return 'DEVELOPMENT_GAIN'


def decide(summaries: dict, axis_states: dict, bcost: dict, recommendation: str | None) -> dict:
    representatives = [g + '_s' + str(REPRESENTATIVE_SEED) for g in L_GROUPS]
    targets = list(B_ARMS) + representatives
    changes = [contrast(summaries, before, after) for before in COMPARATORS for after in targets]
    arms = {a: dict(status=classify(contrast(summaries, 'E0', a)),
                    adoption='HOLD_OPERATIONAL_CHANGE', representative_fixed_before_scoring=True)
            for a in targets}
    # No ranking or primary-best seed selection. This is a transparent descriptive
    # comparison of predeclared representatives, not a new validated selector.
    full = 'D1_H1_MLP_s' + str(REPRESENTATIVE_SEED)
    pair = 'D1_H1_PAIR_MLP_s' + str(REPRESENTATIVE_SEED)
    pair_change = contrast(summaries, full, pair)
    if recommendation:
        next_one, reason = recommendation, 'Explicit root review recommendation; no automatic model selection'
    elif get(bcost, 'geometry_independent_v2/geometry_status') not in ('PASS',):
        next_one = 'B 기하 검산의 미해결 항목 한 가지를 먼저 확정한다.'
        reason = 'Geometry receipt is absent or does not explicitly report PASS'
    else:
        p = get(pair_change, 'populations/PRIMARY192', default={})
        r = get(pair_change, 'populations/REMAINDER143', default={})
        required = ('success_delta', 'translation_mean_delta_cm', 'rotation_mean_delta_deg',
                    'T_gt50cm_delta', 'T_gt100cm_delta', 'R_gt45deg_delta',
                    'translation_cm_P90_delta', 'translation_cm_P95_delta', 'translation_cm_max_delta',
                    'rotation_deg_P90_delta', 'rotation_deg_P95_delta', 'rotation_deg_max_delta')
        known = all(v.get(k) is not None for v in (p, r) for k in required)
        no_loss = known and all(v['success_delta'] >= 0 and all(v[k] <= 0 for k in required[1:]) for v in (p, r))
        if no_loss:
            next_one = '사전 대표 N0↔E0 pair를 비용 축소 후보로 고정하고, 기존 개발자료와 분리된 실사 시험에서 한 번 확인한다.'
