def verify_h1_failure_report_inputs(inputs, summary, rows, seal, evaluation_seal):
    """Validate separate analysis bindings without recomputing pose metrics."""
    if not summary or not seal:
        return False
    bindings = {entry['input']: entry['sha256'] for entry in inputs.bindings}
    expected_arms = [group + '_s' + str(seed) for group in L_GROUPS if '_H1_' in group for seed in SEEDS]
    if summary.get('complete') is not True or seal.get('complete') is not True:
        raise ValueError('Incomplete H1 all-failure reporting input')
    if summary.get('arms') != expected_arms or summary.get('comparators') != ['N0', 'E0', 'E0_REGENERATED']:
        raise ValueError('H1 all-failure arm/reference inventory changed')
    if summary.get('population_denominators') != EXPECTED_N or summary.get('summary_rows') != 180 or len(summary.get('rows', [])) != 180:
        raise ValueError('H1 all-failure full-population/summary inventory changed')
    if summary.get('detail_rows') != len(rows) or seal.get('detail_rows') != len(rows):
        raise ValueError('H1 all-failure detail count differs from saved CSV')
    for name, key in (('H1_ALL_FAILURE_SUMMARY.json', 'h1_all_failure_summary'),
                      ('H1_ALL_FAILURE_ROWS.csv', 'h1_all_failure_rows')):
        if key not in bindings or seal.get('artifacts', {}).get(name) != bindings[key]:
            raise ValueError('H1 all-failure analysis seal artifact mismatch: ' + name)
    if not evaluation_seal.is_file():
        raise ValueError('Missing evaluation seal for H1 all-failure report')
    evaluation_sha = digest(evaluation_seal)
    for value in (summary, seal):
        if get(value, 'input_bindings/evaluation_seal/sha256') != evaluation_sha:
            raise ValueError('H1 all-failure summary/analysis seal differs from this evaluation')
    return True


def status(value: Any) -> str:
    if value is None:
        return MISSING
    if isinstance(value, str):
        return value
    if isinstance(value, bool):
        return 'PASS' if value else 'FAIL'
    return safe(get(value, 'status', 'state', 'result', 'passed', 'complete', default=MISSING))


def explicit_axis(validation: dict, axis: str) -> Any:
    for parent in ('axes', 'checks', 'validation_axes', 'six_axes'):
        obj = validation.get(parent)
        if isinstance(obj, dict) and axis in obj:
            return obj[axis]
        if isinstance(obj, list):
            for row in obj:
                if isinstance(row, dict) and get(row, 'axis', 'name', 'id') == axis:
                    return row
    return validation.get(axis)


class Inputs:
    def __init__(self) -> None:
        self.bindings: list[dict] = []
        self.missing: list[dict] = []

    def load(self, name: str, path: Path | None, *, kind: str = 'json') -> Any:
        if path is None or not path.is_file():
            self.missing.append(dict(input=name, file=path.name if path else None,
                                     status='NOT_AVAILABLE', substituted_zero=False))
            return [] if kind == 'csv' else {}
        before = digest(path)
        if kind == 'csv':
            opener = gzip.open if path.suffix == '.gz' else open
            with opener(path, 'rt', newline='') as f:
                value = list(csv.DictReader(f))
        else:
            value = json.loads(path.read_text())
        if digest(path) != before:
            raise ValueError('Input changed while reporting: ' + name)
        self.bindings.append(dict(input=name, file=path.name, sha256=before,
                                  bytes=path.stat().st_size))
        return value


def publication_snapshot(inputs: Inputs, publication: dict, run: Path, output: Path,
                         explicit_check: Path | None = None) -> dict:
    """Read only the external verified result-A snapshot, never today's pack check.

    A report is itself in the current pack manifest. Binding today's check here
    would create report -> check -> manifest -> report. A's frozen snapshot is
    older than the metadata report and stays unchanged when that report is packed.
    """
    snapshot = publication.get('offline_check_snapshot')
    if not snapshot:
        if explicit_check is not None:
            raise ValueError('--publication-check needs an external result-commit snapshot binding')
        return {}
    result_commit = get(publication, 'result_commit', 'result_commit_sha', 'result_sha')
    if (not result_commit or snapshot.get('result_commit') != result_commit
            or publication.get('status') != 'PUSHED_MAIN_VERIFIED'
            or publication.get('remote_main_contains_result_commit') is not True
            or publication.get('remote_artifacts_verified') is not True):
        raise ValueError('Publication snapshot needs actual externally verified result commit A')
    paths = {}
    for key in ('path', 'manifest_path'):
        relative = Path(snapshot[key])
        if (relative.is_absolute() or '..' in relative.parts or relative.parts[:2] != ('publication_snapshots', 'result_A')):
            raise ValueError('Use the immutable publication_snapshots/result_A directory')
        target = run / relative
        if not target.resolve().is_relative_to((run / 'publication_snapshots' / 'result_A').resolve()):
            raise ValueError('Result snapshot path escaped its immutable directory')
        if target.resolve() == (output / 'PUBLICATION_CHECK.json').resolve() or target.resolve() == (output / 'PUBLICATION_MANIFEST.json').resolve():
            raise ValueError('Current public manifest/check cannot be a report input')
        paths[key] = target
    if explicit_check is not None and explicit_check.resolve() != paths['path'].resolve():
        raise ValueError('--publication-check must be the exact externally bound immutable snapshot')
    check = inputs.load('result_commit_A_offline_check_snapshot', paths['path'])
    manifest = inputs.load('result_commit_A_manifest_snapshot', paths['manifest_path'])
    if not check or not manifest:
        return {}
    if (digest(paths['path']) != snapshot['sha256'] or digest(paths['manifest_path']) != snapshot['manifest_sha256']
            or check.get('manifest_sha256') != snapshot['manifest_sha256']
            or check.get('status') != 'PASS' or snapshot.get('status') != 'PASS'):
        raise ValueError('Immutable result-A offline check/manifest bytes or binding changed')
    return dict(check, snapshot_result_commit=result_commit,
                snapshot_check_sha256=snapshot['sha256'], snapshot_manifest_sha256=snapshot['manifest_sha256'])


def normalize(results: dict, comparison: list[dict]) -> dict:
    source = get(results, 'populations', 'summaries', default={})
    out = {p: dict(source.get(p, {})) for p in POPULATIONS}
    # Explicit CSV fallback supports reports assembled from compact public data.
    for row in comparison:
        pop, arm = row.get('population'), row.get('arm')
        if pop not in out or arm not in ALL_ARMS or arm in out[pop]:
            continue
        value: dict = {}
        for key, raw in row.items():
            if key in ('population', 'arm'):
                continue
            v: Any = None
            if raw not in ('', None, 'None', 'null', 'N/A'):
                try:
                    n = float(raw)
                    v = int(n) if n.is_integer() and key in (
                        'denominator', 'successes', 'no_pose', 'T_gt50cm', 'T_gt100cm', 'R_gt45deg') else n
                except ValueError:
                    v = raw
            if '/' in key:
                parent, field = key.split('/', 1)
                value.setdefault(parent, {})[field] = v
            else:
                value[key] = v
        out[pop][arm] = value
    return out


def distribution(record: dict, key: str) -> list[Any]:
    d = record.get(key) or {}
    sd = get(d, 'sample_std', 'sample_SD', 'SD_ddof1', 'std', 'SD')
    variance = get(d, 'variance_ddof1', 'sample_variance', 'variance')
    if variance is None and isinstance(sd, (int, float)):
        variance = sd * sd  # exact definition, not an invented measurement
    return [number(get(d, 'n', 'available_n')), number(get(d, 'mean')),
            number(variance), number(sd), number(get(d, 'median')),
            number(get(d, 'P90', 'p90')), number(get(d, 'P95', 'p95')),
            number(get(d, 'max'))]


def summary_row(pop: str, arm: str, summaries: dict) -> list[Any]:
    r = summaries.get(pop, {}).get(arm, {})
    k, n = r.get('successes'), r.get('denominator')
    rate = r.get('success_rate')
    if rate is None and isinstance(k, (int, float)) and isinstance(n, (int, float)) and n:
        rate = k / n
    return [arm, number(n), number(k), number(100 * rate) + '%' if rate is not None else MISSING,
            number(r.get('no_pose')), number(r.get('T_gt50cm')),
            number(r.get('T_gt100cm')), number(r.get('R_gt45deg'))]


