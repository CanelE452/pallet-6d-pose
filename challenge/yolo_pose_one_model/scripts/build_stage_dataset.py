"""Assemble a stage dataset from prepared frames and write its data YAML.

Stage A composition (synthetic only, this round):
    generic train  x1   (~38k)
    target  train  x2   (~18k -> ~36k effective)  => roughly 1:1 generic:target
    val = generic val + target val, each frame once

Repeats are unique-named symlinks (hardlink, then copy, as fallbacks). The same file is
never listed twice under one name, because a loader may deduplicate identical paths.

The YAML `path` is written as an ABSOLUTE path computed at build time. Ultralytics
resolves a relative `path` against SETTINGS['datasets_dir'], not the repo, so a
repo-relative string would silently point somewhere else. Nothing is hardcoded in
source: the path is derived from this file's location.

Usage:
  python .../build_stage_dataset.py --stage stage_a --target-repeat 2
  python .../build_stage_dataset.py --yaml-only --stage smoke
"""
from __future__ import annotations

import argparse
import json
import os
import shutil
from pathlib import Path

REPO = Path(__file__).resolve().parents[3]
OUT = REPO / "challenge/yolo_pose_one_model"

YAML_TMPL = """# generated by scripts/build_stage_dataset.py -- do not edit by hand
# absolute path computed at build time (Ultralytics resolves a relative `path`
# against SETTINGS['datasets_dir'], which is not this repo)
path: {root}
train: images/train
val: images/val

nc: 1

names:
  0: pallet

kpt_shape: [9, 3]

# data contract only; fliplr is 0.0 in every config this round
flip_idx: [1, 0, 3, 2, 5, 4, 7, 6, 8]
"""


def link(src: Path, dst: Path):
    if dst.exists() or dst.is_symlink():
        return "exists"
    try:
        # Relative target: src and dst are siblings, so a bare filename keeps the link
        # valid when the dataset directory is copied or moved to another machine.
        # An absolute target would break the moment the tree lands under a new path.
        os.symlink(os.path.relpath(src, dst.parent), dst)
        return "symlink"
    except OSError:
        pass
    try:
        os.link(src, dst)
        return "hardlink"
    except OSError:
        shutil.copy2(src, dst)
        return "copy"


def add_repeats(root: Path, split: str, prefix: str, repeat: int):
    """Create repeat-1 extra aliases for every frame whose stem starts with prefix."""
    img_dir = root / "images" / split
    lbl_dir = root / "labels" / split
    base = [p for p in sorted(img_dir.glob(f"{prefix}*.png")) if "__rep" not in p.stem]
    modes = {}
    made = 0
    for p in base:
        lp = lbl_dir / f"{p.stem}.txt"
        if not lp.exists():
            continue
        for k in range(1, repeat):
            alias = f"{p.stem}__rep{k}"
            m = link(p.resolve(), img_dir / f"{alias}.png")
            link(lp.resolve(), lbl_dir / f"{alias}.txt")
            modes[m] = modes.get(m, 0) + 1
            made += 1
    return len(base), made, modes


def write_yaml(stage: str):
    root = (OUT / "datasets" / stage).resolve()
    cfg = OUT / "configs" / f"{stage}.yaml"
    cfg.parent.mkdir(parents=True, exist_ok=True)
    cfg.write_text(YAML_TMPL.format(root=root), encoding="utf-8")
    print(f"wrote {cfg.relative_to(REPO)}  (path={root})")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--stage", required=True)
    ap.add_argument("--target-repeat", type=int, default=1,
                    help="how many times each target_synth train frame appears")
    ap.add_argument("--yaml-only", action="store_true")
    args = ap.parse_args()

    root = OUT / "datasets" / args.stage
    if not args.yaml_only:
        if args.target_repeat > 1:
            n_base, n_made, modes = add_repeats(root, "train", "T__", args.target_repeat)
            print(f"target repeats: base={n_base} aliases={n_made} modes={modes}")
        counts = {}
        for split in ("train", "val"):
            d = root / "images" / split
            if d.exists():
                imgs = list(d.glob("*.png"))
                counts[split] = {
                    "total": len(imgs),
                    "generic": sum(1 for p in imgs if p.name.startswith("G__")),
                    "target": sum(1 for p in imgs if p.name.startswith("T__")),
                    "target_alias": sum(1 for p in imgs if "__rep" in p.stem),
                }
        print(json.dumps(counts, indent=2))
        json.dump({"stage": args.stage, "target_repeat": args.target_repeat,
                   "counts": counts},
                  open(root / "_composition.json", "w", encoding="utf-8"), indent=2)
    write_yaml(args.stage)


if __name__ == "__main__":
    main()
